D, VOCAB = 512, 4096
WARMUP_STEPS = 12
STEADY_STEPS = 20
PRECISIONS = {
    "fp32": {"storage_dtype": None, "ecc": None},
    "bf16": {"storage_dtype": torch.bfloat16, "ecc": None},
    "ecc8": {"storage_dtype": None, "ecc": 8},
    "ecc16": {"storage_dtype": None, "ecc": 16},
}


try:
    _feature_test = importlib.import_module("test.test_feature_matrix")
    _TEST_D = _feature_test.D
    _TEST_VOCAB = _feature_test.VOCAB
    Transformer = _feature_test.Transformer

    if (_TEST_D, _TEST_VOCAB) != (D, VOCAB):
        raise ValueError("test/test_feature_matrix.py uses unexpected model dimensions")
except Exception:

    class Transformer(nn.Module):
        """Exact fallback for test/test_feature_matrix.py's Transformer."""

        def __init__(self):
            super().__init__()
            self.embed = nn.Embedding(VOCAB, D)
            self.in_proj = nn.Linear(D, 3 * D)
            self.out = nn.Linear(D, D)
            self.up = nn.Linear(D, 4 * D)
            self.down = nn.Linear(4 * D, D)
            self.norm = nn.LayerNorm(D)
            self.head = nn.Linear(D, VOCAB)

        def forward(self, idx):
            x = self.embed(idx).mean(1)
            q, k, v = self.in_proj(x).chunk(3, dim=-1)
            x = self.out(torch.tanh(q) * torch.sigmoid(k) + v)
            return self.head(self.norm(x + self.down(F.gelu(self.up(x)))))


def _remove_cache_root() -> None:
    if _CACHE_ROOT.exists():
        shutil.rmtree(_CACHE_ROOT)


atexit.register(_remove_cache_root)


def _clear_inductor_cache() -> None:
    """Clear Inductor's in-memory caches and this process's on-disk cache."""

    torch._inductor.utils.clear_caches()
    if _CACHE_ROOT.exists():
        shutil.rmtree(_CACHE_ROOT)
    _CACHE_ROOT.mkdir(parents=True)


def _reset_between_cells() -> None:
    gc.collect()
    torch._dynamo.reset()
    torch._dynamo.utils.counters.clear()
    torch.cuda.empty_cache()


def _discover_optimizers() -> list[str]:
    """Apply test/test_feature_matrix.py's class rule, minus external producers."""

    return sorted(
        name
        for name in dir(heavyball)
        if isinstance(getattr(heavyball, name), type)
        and issubclass(getattr(heavyball, name), heavyball.HeavyBallOptimizer)
        and getattr(heavyball, name) is not heavyball.HeavyBallOptimizer
        and not name.startswith("TrueGrad")
    )


def _state_slabs(opt: heavyball.HeavyBallOptimizer) -> list[torch.Tensor]:
    return [
        slab
        for engine in opt._engines
        for group in engine.groups
        for slots in (*group.states, group.commit_state)
        for slab in slots.values()
    ]


def _run_training_step(
    model: nn.Module,
    opt: heavyball.HeavyBallOptimizer,
    idx: torch.Tensor,
    target: torch.Tensor,
    *,
    step_type: str | None = None,
) -> None:
    opt.zero_grad()
    loss = F.cross_entropy(model(idx), target)
    loss.backward()
    if step_type is None:
        # The timed path uses the facade and its real host-side refresh cadence.
        opt.step()
    else:
        # Explicit warmup compiles both fullgraph artifacts independent of cadence.
        opt._sync_hypers_from_groups(force=False)
        opt._engine.step(step_type=step_type)


def _timed_step(
    model: nn.Module,
    opt: heavyball.HeavyBallOptimizer,
    idx: torch.Tensor,
    target: torch.Tensor,
    *,
    step_type: str | None = None,
) -> float:
    torch.cuda.synchronize()
    started = time.perf_counter()
    _run_training_step(model, opt, idx, target, step_type=step_type)
    torch.cuda.synchronize()
    return time.perf_counter() - started


def _unique_graphs() -> int:
    return int(torch._dynamo.utils.counters["stats"]["unique_graphs"])


def _recompile_events() -> int:
    return sum(int(value) for value in torch._dynamo.utils.counters.get("recompiles", {}).values())


def _measure_cell(name: str, feature: str) -> dict[str, object]:
    facade = getattr(heavyball, name)
    torch.manual_seed(0)
    torch.cuda.manual_seed_all(0)
    model = Transformer().cuda()
    idx = torch.randint(VOCAB, (4, 8), device="cuda")
    target = torch.randint(VOCAB, (4,), device="cuda")
    lr = inspect.signature(facade).parameters["lr"].default
    opt = facade(model.parameters(), lr=lr, **PRECISIONS[feature])

    # Finish allocation/lazy CUDA setup before resetting the peak and starting
    # the cold-step clock.  The reported peak still includes all live model and
    # optimizer allocations because reset_peak_memory_stats resets the watermark.
    torch.cuda.synchronize()
    torch.cuda.reset_peak_memory_stats()

    compile_s = _timed_step(model, opt, idx, target, step_type="normal")

    # Force the alternate optimizer graph once, then give kernels and allocator
    # twelve total untimed steps before measuring production cadence.
    _run_training_step(model, opt, idx, target, step_type="refresh")
    for _ in range(WARMUP_STEPS - 1):
        _run_training_step(model, opt, idx, target)
    torch.cuda.synchronize()

    graph_count = _unique_graphs()
    recompiles_before = _recompile_events()
    elapsed: list[float] = []
    steady_graph_counts: list[int] = []
    for _ in range(STEADY_STEPS):
        elapsed.append(_timed_step(model, opt, idx, target))
        steady_graph_counts.append(_unique_graphs())

    recompiles_after = _recompile_events()
    try:
        assert 0 < graph_count <= 2
        assert recompiles_before == 0
        assert all(count == graph_count for count in steady_graph_counts)
        assert recompiles_after == recompiles_before
    except AssertionError:
        recompile_contaminated = True
    else:
        recompile_contaminated = False

    slabs = _state_slabs(opt)
    float_slabs = [slab for slab in slabs if slab.is_floating_point()]
    mean_step_ms = 1000.0 * sum(elapsed) / len(elapsed)
    record: dict[str, object] = {
        "opt": name,
        "feat": feature,
        "compile_s": round(compile_s, 3),
        "step_ms": None if recompile_contaminated else round(mean_step_ms, 3),
        "peak_mb": round(torch.cuda.max_memory_allocated() / 1e6, 2),
        "state_mb": round(
            sum(slab.numel() * slab.element_size() for slab in float_slabs) / 1e6,
            2,
        ),
        "n_slabs": len(slabs),
        "recompile_contaminated": recompile_contaminated,
    }
    assert math.isfinite(compile_s)
    assert recompile_contaminated or math.isfinite(mean_step_ms)
    return record


def _append_record(path: Path, record: dict[str, object]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as handle:
        handle.write(json.dumps(record, allow_nan=False, sort_keys=True) + "\n")


def main(args: argparse.Namespace | None = None) -> int:
    if args is None:
        args = _arguments()
    if args.render is not None:
        return _render(args.render, args.out, args.update_readme)
    if not torch.cuda.is_available():
        raise SystemExit("CUDA is required for the compiled feature-matrix benchmark")

    optimizers = _discover_optimizers()
    if args.shard is not None:
        idx, total = args.shard
        optimizers = [name for i, name in enumerate(optimizers) if i % total == idx]
    precisions = args.precisions
    if args.smoke:
        optimizers = ["AdamW", "SOAP"]
        precisions = ["fp32"]
    elif args.limit is not None:
        optimizers = optimizers[: args.limit]

    records: list[dict[str, object]] = []
    for feature in precisions:
        # Share compiled kernels within a precision so per-cell cost is a warm
        # re-trace (fast), not a cold max-autotune compile. step_ms stays
        # trustworthy: _measure_cell's warmup still forces the refresh graph
        # before the timed window. Clear once per precision to bound disk.
        _clear_inductor_cache()
        for name in optimizers:
            _reset_between_cells()
            record = _measure_cell(name, feature)
            records.append(record)
            if args.measure is not None:
                _append_record(args.measure, record)
            if args.smoke:
                value = record["step_ms"]
                rendered = "recompile" if value is None else f"{float(value):.3f}"
                print(f"{name} fp32 step_ms={rendered}", flush=True)

    if not args.smoke:
        markdown = _markdown(records, optimizers)
        print(markdown, end="")
        if args.out is not None:
            args.out.parent.mkdir(parents=True, exist_ok=True)
            args.out.write_text(markdown, encoding="utf-8")

    flagged = sum(bool(record["recompile_contaminated"]) for record in records)
    print(
        f"{len(optimizers)} optimizers x {len(precisions)} = "
        f"{len(records)} cells, {flagged} flagged recompile-contaminated",
        flush=True,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main(_CLI_ARGS))
