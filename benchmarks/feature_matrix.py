#!/usr/bin/env python3
"""Benchmark HeavyBall's optimizer x state-precision feature matrix.

The benchmark deliberately measures the production compiled optimizer path.  Each
cell gets a cold normal step, an explicitly forced refresh step, twelve warmup
steps, and a twenty-step steady window guarded against recompilation.
"""

